-- ------------------------------------------------------------
-- Seed data: reproduces the old single-call behaviour as one
-- chain, adds a two-step brainstorm-then-polish chain, and splits
-- traffic 50/50 between them.
-- ------------------------------------------------------------

insert into llm_providers (name) values ('Google')
on conflict (name) do nothing;

insert into llm_models (provider_id, name, model_identifier, temperature)
select id, 'Gemini 3.8 Flash', 'gemini-3.8-flash', 1.0
from llm_providers where name = 'Google'
on conflict (provider_id, model_identifier) do nothing;

insert into prompt_chains (name, description) values
  ('Classic one-liner', 'Single call: write one witty caption directly.'),
  ('Brainstorm then polish', 'Step 1 drafts three ideas, step 2 picks and sharpens the best one.')
on conflict (name) do nothing;

insert into prompt_chain_steps (chain_id, step_order, llm_model_id, prompt_template)
select c.id, 1, m.id,
  'You write short, funny captions for CUmor, a humor app for Columbia students.

Campus terms you can use:
{{terms}}

Captions our users loved:
{{examples}}

Write one witty one-or-two sentence caption about: {{input}}
Respond with only the caption text, no quotes, no extra commentary.'
from prompt_chains c, llm_models m
where c.name = 'Classic one-liner' and m.model_identifier = 'gemini-3.8-flash'
on conflict (chain_id, step_order) do nothing;

insert into prompt_chain_steps (chain_id, step_order, llm_model_id, prompt_template)
select c.id, 1, m.id,
  'You brainstorm jokes for CUmor, a humor app for Columbia students.

Campus terms you can use:
{{terms}}

Captions our users loved:
{{examples}}

Brainstorm three different short funny caption ideas about: {{input}}
Number them 1-3, one per line.'
from prompt_chains c, llm_models m
where c.name = 'Brainstorm then polish' and m.model_identifier = 'gemini-3.8-flash'
on conflict (chain_id, step_order) do nothing;

insert into prompt_chain_steps (chain_id, step_order, llm_model_id, prompt_template)
select c.id, 2, m.id,
  'Here are caption ideas about "{{input}}":
{{previous}}

Pick the funniest one and polish it into a single witty caption of at most two sentences.
Respond with only the caption text, no quotes, no numbering, no extra commentary.'
from prompt_chains c, llm_models m
where c.name = 'Brainstorm then polish' and m.model_identifier = 'gemini-3.8-flash'
on conflict (chain_id, step_order) do nothing;

insert into prompt_chain_mix (chain_id, weight)
select id, 1 from prompt_chains
on conflict (chain_id) do nothing;

