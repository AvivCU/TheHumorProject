create policy "Users read own requests" on generation_requests
  for select to authenticated using (user_id = auth.uid());
drop policy if exists "Superadmins read all requests" on generation_requests;
create policy "Superadmins read all requests" on generation_requests
  for select using (public.is_superadmin());

drop policy if exists "Users log responses for own requests" on llm_responses;
create policy "Users log responses for own requests" on llm_responses
  for insert to authenticated
  with check (exists (
    select 1 from generation_requests r
    where r.id = request_id and r.user_id = auth.uid()
  ));
drop policy if exists "Superadmins read all responses" on llm_responses;
create policy "Superadmins read all responses" on llm_responses
  for select using (public.is_superadmin());

drop policy if exists "Superadmins manage signup domains" on allowed_signup_domains;
create policy "Superadmins manage signup domains" on allowed_signup_domains
  for all using (public.is_superadmin()) with check (public.is_superadmin());

