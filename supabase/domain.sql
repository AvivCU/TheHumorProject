-- ============================================================
-- Week 7: Domain model
-- Caption generation now runs through configurable prompt chains
-- backed by LLM providers/models, and every request and LLM call
-- is logged. Run once in the Supabase SQL Editor, after admin.sql.
-- ============================================================

create table if not exists llm_providers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists llm_models (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references llm_providers (id) on delete restrict,
  name text not null,
  model_identifier text not null,
  temperature numeric(3, 2) not null default 1.0 check (temperature between 0 and 2),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (provider_id, model_identifier)
);

create table if not exists prompt_chains (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

-- Templates can use {{input}}, {{previous}}, {{terms}} and {{examples}}.
create table if not exists prompt_chain_steps (
  id bigint generated by default as identity primary key,
  chain_id bigint not null references prompt_chains (id) on delete cascade,
  step_order integer not null check (step_order > 0),
  llm_model_id bigint not null references llm_models (id) on delete restrict,
  prompt_template text not null,
  created_at timestamptz not null default now(),
  unique (chain_id, step_order)
);

-- How often each chain is picked: weight / sum(active weights).
create table if not exists prompt_chain_mix (
  id bigint generated by default as identity primary key,
  chain_id bigint not null unique references prompt_chains (id) on delete cascade,
  weight numeric(6, 2) not null default 1 check (weight >= 0),
  is_active boolean not null default true,
  updated_at timestamptz not null default now()
);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists prompt_chain_mix_touch on prompt_chain_mix;
create trigger prompt_chain_mix_touch
  before update on prompt_chain_mix
  for each row execute function public.touch_updated_at();

create table if not exists terms (
  id bigint generated by default as identity primary key,
  term text not null unique,
  definition text not null,
  example text,
  created_at timestamptz not null default now()
);

create table if not exists generation_examples (
  id bigint generated by default as identity primary key,
  prompt text not null,
  caption text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists generation_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users (id) on delete set null,
  chain_id bigint references prompt_chains (id) on delete set null,
  prompt text not null,
  status text not null default 'pending'
    check (status in ('pending', 'completed', 'failed')),
  error text,
  generation_id bigint references generations (id) on delete set null,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists llm_responses (
  id bigint generated by default as identity primary key,
  request_id bigint not null references generation_requests (id) on delete cascade,
  step_id bigint references prompt_chain_steps (id) on delete set null,
  llm_model_id bigint references llm_models (id) on delete set null,
  step_order integer,
  input_text text not null,
  output_text text,
  http_status integer,
  latency_ms integer,
  created_at timestamptz not null default now()
);

create table if not exists allowed_signup_domains (
  id bigint generated by default as identity primary key,
  domain text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists whitelisted_emails (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now()
);

-- ------------------------------------------------------------
-- RLS
-- Pipeline config is readable by any signed-in user because the
-- generate route runs with the user's own session. Only
-- superadmins can change it, and only through the operations the
-- admin app is meant to offer (chains/steps are read-only there,
-- the mix is update-only).
-- ------------------------------------------------------------

alter table llm_providers enable row level security;
alter table llm_models enable row level security;
alter table prompt_chains enable row level security;
alter table prompt_chain_steps enable row level security;
alter table prompt_chain_mix enable row level security;
alter table terms enable row level security;
alter table generation_examples enable row level security;
alter table generation_requests enable row level security;
alter table llm_responses enable row level security;
alter table allowed_signup_domains enable row level security;
alter table whitelisted_emails enable row level security;

drop policy if exists "Signed-in users read providers" on llm_providers;
create policy "Signed-in users read providers" on llm_providers
  for select to authenticated using (true);
drop policy if exists "Superadmins manage providers" on llm_providers;
create policy "Superadmins manage providers" on llm_providers
  for all using (public.is_superadmin()) with check (public.is_superadmin());

