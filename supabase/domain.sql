  for all using (public.is_superadmin()) with check (public.is_superadmin());

drop policy if exists "Users create own requests" on generation_requests;
create policy "Users create own requests" on generation_requests
  for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "Users update own requests" on generation_requests;
create policy "Users update own requests" on generation_requests
  for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
